import Foundation

/// What is safe to delete, and what it would actually give back.
///
/// The design rule here is that a name is never enough. `build` is a compiler's
/// output directory in one project and a decade of someone's work in another,
/// so every rule demands evidence — a `package.json` beside `node_modules`, a
/// `Cargo.toml` beside `target` — and a directory that cannot produce it is
/// simply not offered. Being useless is recoverable; being wrong is not.
///
/// Sizes are reported as `retained`, never as the naive total: a DerivedData
/// folder full of clones gives back far less than it appears to hold, and an
/// estimate that overshoots is how a cleanup tool loses someone's trust.
enum Reclaim {
    enum Confidence: Int, Comparable {
        /// Regenerated by a tool from files that are still there.
        case regenerable
        /// A cache: regenerable by definition, costs time rather than data.
        case cache
        /// Big, often unwanted, and *not* reconstructible. Reported for a
        /// human to judge, never deleted by this program.
        case review

        static func < (a: Confidence, b: Confidence) -> Bool { a.rawValue < b.rawValue }

        var label: String {
            switch self {
            case .regenerable: return tr(en: "REGENERABLE", fr: "REGÉNÉRABLE")
            case .cache: return tr(en: "CACHE", fr: "CACHE")
            case .review: return tr(en: "YOUR CALL", fr: "À VOTRE APPRÉCIATION")
            }
        }
        /// Lower-case form for the inspector, the legend and the sheet.
        var title: String {
            switch self {
            case .regenerable: return tr(en: "regenerable", fr: "régénérable")
            case .cache: return tr(en: "cache", fr: "cache")
            case .review: return tr(en: "your call", fr: "à votre appréciation")
            }
        }
        var blurb: String {
            switch self {
            case .regenerable:
                return tr(en: "rebuilt by a tool from files that are still there",
                          fr: "reconstruit par un outil, à partir de fichiers toujours présents")
            case .cache:
                return tr(en: "refills itself — you lose time, not data",
                          fr: "se reremplit tout seul — on perd du temps, pas des données")
            case .review:
                return tr(en: "large and often unwanted, but irreplaceable — never deleted automatically",
                          fr: "volumineux et souvent inutile, mais irremplaçable — jamais supprimé automatiquement")
            }
        }
    }

    enum Match {
        /// A directory with this exact name, anywhere under the scan.
        case named(String)
        /// Every direct child of this path.
        case childrenOf(String)
        /// This one directory.
        case exact(String)
    }

    struct Rule {
        let id: String
        let label: String
        let confidence: Confidence
        let match: Match
        /// At least one of these must sit beside the directory.
        var siblings: [String] = []
        /// At least one of these must sit inside it.
        var contents: [String] = []
        /// How the content comes back.
        let recovery: String
    }

    struct Candidate {
        var node: Int32
        var path: String
        var rule: Rule
        var sizes: Sizes
        var modified: Date?

        var age: TimeInterval? { modified.map { Date().timeIntervalSince($0) } }
    }

