    // MARK: - Guards

    /// Places this program will not propose to delete from, whatever a rule
    /// matched. The read-only system volume, anything managed by the OS, and
    /// application bundles.
    private static let forbidden = [
        "/System", "/usr", "/bin", "/sbin", "/Applications", "/Library/Apple",
        "/private/var/db", "/private/var/folders", "/Volumes/Recovery",
    ]

    static func isProtected(_ path: String) -> Bool {
        // /usr/local and /opt are user territory; the rest of /usr is not.
        // Checked first: `/usr` is in the forbidden list, and the prefix test
        // would otherwise claim Homebrew's whole tree for the system.
        if path == "/usr/local" || path.hasPrefix("/usr/local/") || path == "/opt" || path.hasPrefix("/opt/") {
            return false
        }
        return forbidden.contains(where: { path == $0 || path.hasPrefix($0 + "/") })
    }

    private static func exists(_ path: String) -> Bool {
        var info = stat()
        return lstat(path, &info) == 0
    }

    /// Re-checked both when reporting and again immediately before deleting,
    /// because a scan is a photograph and the disk keeps moving.
    static func verify(_ path: String, rule: Rule) -> String? {
        var info = stat()
        guard lstat(path, &info) == 0 else { return tr(en: "has disappeared", fr: "a disparu") }
        // The symlink test has to come before the directory test: lstat
        // reports a link as a link, so the other order never named it.
        if (info.st_mode & S_IFMT) == S_IFLNK { return tr(en: "is a symbolic link", fr: "est un lien symbolique") }
        guard (info.st_mode & S_IFMT) == S_IFDIR else { return tr(en: "is no longer a folder", fr: "n'est plus un dossier") }
        if isProtected(path) { return tr(en: "is in a protected area", fr: "est dans une zone protégée") }

        // A working tree is not build output, whatever it is called.
        if exists(path + "/.git") { return tr(en: "contains a git repository", fr: "contient un dépôt git") }

        let parent = (path as NSString).deletingLastPathComponent
        if !rule.siblings.isEmpty {
            let found = rule.siblings.first { exists(parent + "/" + $0) }
            guard found != nil else {
                return tr(en: "no %@ beside it", fr: "aucun %@ à côté",
                          rule.siblings.joined(separator: tr(en: " or ", fr: " ou ")))
            }
        }
        if !rule.contents.isEmpty {
            let found = rule.contents.first { exists(path + "/" + $0) }
            guard found != nil else {
                return tr(en: "does not contain %@", fr: "ne contient pas %@",
                          rule.contents.joined(separator: tr(en: " or ", fr: " ou ")))
            }
        }
        return nil
    }

    struct Findings {
        var candidates: [Candidate] = []
        /// Matches too small to be worth a line. A tree of `__pycache__`
        /// directories is real and correctly identified, and listing forty of
        /// them at a few kilobytes each buries the two that matter.
        ///
        /// The floor is on apparent size, never on what the entry gives back:
        /// a 24 MB `node_modules` that retains nothing — because its twin
        /// holds the same hard links — is precisely the case worth showing.
        var ignoredCount = 0
        var ignoredBytes: Int64 = 0

        var removable: [Candidate] { candidates.filter { $0.rule.confidence != .review } }
    }

    // MARK: - Finding

    static func find(in result: ScanResult, minimum: Int64 = 1 << 20) -> Findings {
        var findings = Findings()
        for candidate in candidates(in: result) {
            if candidate.sizes.attributed < minimum && candidate.rule.confidence != .review {
                findings.ignoredCount += 1
                findings.ignoredBytes += candidate.sizes.attributed
            } else {
                findings.candidates.append(candidate)
            }
        }
        return findings
    }

    static func candidates(in result: ScanResult) -> [Candidate] {
        let tree = result.tree
        var byName: [String: [Rule]] = [:]
        var anchored: [Rule] = []
        for rule in catalogue {
            switch rule.match {
            case .named(let name): byName[name, default: []].append(rule)
            case .childrenOf, .exact: anchored.append(rule)
            }
        }

        var hits: [(Int32, Rule)] = []
        for node in 0..<tree.count {
            guard let rules = byName[tree.name[node]] else { continue }
            for rule in rules { hits.append((Int32(node), rule)) }
        }
        for rule in anchored {
            switch rule.match {
            case .childrenOf(let path):
                guard let anchor = tree.node(at: path) else { continue }
                for child in tree.children[Int(anchor)] { hits.append((child, rule)) }
            case .exact(let path):
                guard let node = tree.node(at: path) else { continue }
                hits.append((node, rule))
            default: break
            }
        }

        var candidates: [Candidate] = []
        var claimed = Set<Int32>()
        for (node, rule) in hits {
            guard !claimed.contains(node) else { continue }
            let path = tree.path(of: node)
            guard verify(path, rule: rule) == nil else { continue }
            claimed.insert(node)

            var info = stat()
            let modified = lstat(path, &info) == 0
                ? Date(timeIntervalSince1970: TimeInterval(info.st_mtimespec.tv_sec)) : nil
            candidates.append(Candidate(node: node, path: path, rule: rule,
                                        sizes: tree.total[Int(node)], modified: modified))
        }

        // A `node_modules` inside a `node_modules` is already accounted for by
        // its ancestor; reporting both would double every number.
        let ancestors = Set(candidates.map { $0.node })
        candidates = candidates.filter { candidate in
            var parent = tree.parent[Int(candidate.node)]
            while parent >= 0 {
                if ancestors.contains(parent) { return false }
                parent = tree.parent[Int(parent)]
            }
            return true
        }

        return candidates.sorted { $0.sizes.retained > $1.sizes.retained }
    }

    /// Bytes actually freed by removing all of these at once — see
    /// `Families.bytesFreed`, which is where the sharing is resolved.
    static func combinedFreed(_ candidates: [Candidate], in result: ScanResult) -> Int64 {
        let tree = result.tree
        var marked = [Bool](repeating: false, count: tree.count)
        var stack = candidates.map { $0.node }
        while let node = stack.popLast() {
            guard !marked[Int(node)] else { continue }
            marked[Int(node)] = true
            stack.append(contentsOf: tree.children[Int(node)])
        }
        return result.families.bytesFreed(deleting: marked, plainBytes: tree.plainBytes)
    }
}

extension Tree {
    /// Locate a node by absolute path, descending from the scan root.
    func node(at absolutePath: String) -> Int32? {
        guard let rootPath = name.first else { return nil }
        let root = rootPath == "/" ? "" : rootPath
        guard absolutePath == rootPath || absolutePath.hasPrefix(root + "/") else { return nil }
        let tail = String(absolutePath.dropFirst(root.count))
        var current: Int32 = 0
        for component in tail.split(separator: "/") {
            guard let next = children[Int(current)].first(where: { name[Int($0)] == component })
            else { return nil }
            current = next
        }
        return current
    }
}

extension Renderer {
    func reclaimSection(_ findings: Reclaim.Findings, in result: ScanResult,
                        volume: VolumeReport, offerTrash: Bool = true) -> String {
        let candidates = findings.candidates
        let heading = Style.bold(tr(en: "TO RECLAIM\n", fr: "À RÉCUPÉRER\n"))
        guard !candidates.isEmpty else {
            return heading + "  " + Style.green(tr(en: "nothing here can be identified as safe to delete",
                                                   fr: "rien d'identifiable comme sûr à supprimer ici")) + "\n"
        }

        var out = heading
        let removable = candidates.filter { $0.rule.confidence != .review }
        let combined = Reclaim.combinedFreed(removable, in: result)
        let individually = removable.reduce(0) { $0 + $1.sizes.retained }

        for confidence in [Reclaim.Confidence.regenerable, .cache, .review] {
            let group = candidates.filter { $0.rule.confidence == confidence }
            guard !group.isEmpty else { continue }
            let total = group.reduce(0) { $0 + $1.sizes.retained }

            out += "\n  " + Style.bold(confidence.label)
            out += Style.dim("  \(confidence.blurb)")
            out += "   " + Style.bold(humanBytes(total)) + "\n"

            for candidate in group.prefix(topCount) {
                let shared = candidate.sizes.attributed - candidate.sizes.retained
                out += "  " + humanBytes(candidate.sizes.retained).padded(10)
                out += " \(candidate.path)\n"
                var notes = [candidate.rule.label]
                if let age = candidate.age {
                    notes.append(tr(en: "modified %@ ago", fr: "modifié il y a %@", humanDuration(age)))
                }
                if shared > 10 << 20 {
                    notes.append(Style.yellow(tr(en: "%@ shared outside this folder",
                                                 fr: "%@ partagés hors de ce dossier", humanBytes(shared))))
                }
                out += Style.dim("             " + notes.joined(separator: " · "))
                if confidence != .review {
                    out += Style.dim("  →  \(candidate.rule.recovery)")
                }
                out += "\n"
            }
            if group.count > topCount {
                out += Style.dim(tr(en: "             … and %d more\n", fr: "             … et %d autres\n", group.count - topCount))
            }
            if confidence == .review {
                out += Style.dim(tr(en: "             cadastre never deletes these entries\n",
                                    fr: "             cadastre ne supprime jamais ces entrées\n"))
            }
        }

        out += "\n  " + Style.bold(tr(en: "TOTAL RECLAIMABLE  ", fr: "TOTAL RÉCUPÉRABLE  ") + humanBytes(combined)) + "\n"
        if findings.ignoredCount > 0 {
            out += Style.dim(tr(en: "  %d entries under 1 MB not listed (%@ in total)\n",
                                fr: "  %d entrées sous 1 Mo non listées (%@ au total)\n",
                                findings.ignoredCount, humanBytes(findings.ignoredBytes)))
        }
        if combined - individually > 1 << 20 {
            out += Style.dim(tr(en: "  that is %@ more than deleting them one by one — these folders share blocks with each other\n",
                                fr: "  soit %@ de plus qu'en les supprimant un par un — ces dossiers partagent des blocs entre eux\n",
                                humanBytes(combined - individually)))
        }
        if !volume.snapshots.isEmpty {
            out += "  " + Style.yellow("⚠ ")
            out += tr(en: "%d local snapshot(s): the space only comes back when they expire\n",
                      fr: "%d snapshot(s) local(aux) : l'espace ne reviendra qu'à leur expiration\n", volume.snapshots.count)
            out += Style.dim(tr(en: "     tmutil deletelocalsnapshots / to force it, if you know what you are doing\n",
                                fr: "     tmutil deletelocalsnapshots / pour forcer, si vous savez ce que vous faites\n"))
        }
        if offerTrash {
            out += Style.dim(tr(en: "\n  --trash to move them to the Trash (never rm), --trash --yes without confirmation\n",
                                fr: "\n  --trash pour mettre à la corbeille (jamais rm), --trash --yes sans confirmation\n"))
        }
        return out
    }
}

extension Reclaim {
    /// Move the deletable candidates to the Trash.
    ///
    /// The Trash and not `unlink`: every judgement in this file is a heuristic,
    /// and a heuristic needs an undo. Every path is re-verified here rather
    /// than trusted from the scan, because the scan may be minutes old.
    static func trash(_ candidates: [Candidate], in result: ScanResult, confirm: Bool) -> Int {
        let removable = candidates.filter { $0.rule.confidence != .review }
        guard !removable.isEmpty else {
            print(tr(en: "  nothing to move to the Trash", fr: "  rien à mettre à la corbeille"))
            return 0
        }

        if confirm {
            let total = combinedFreed(removable, in: result)
            print(tr(en: "\n  %d folders to the Trash, %@ to reclaim.",
                     fr: "\n  %d dossiers vers la corbeille, %@ à récupérer.", removable.count, humanBytes(total)))
            print(tr(en: "  Type “yes” to confirm: ", fr: "  Taper « oui » pour confirmer : "), terminator: "")
            let accepted = ["yes", "y", "oui", "o"]
            guard let answer = readLine()?.trimmingCharacters(in: .whitespacesAndNewlines).lowercased(),
                  accepted.contains(answer) else {
                print(tr(en: "  cancelled, nothing was touched", fr: "  annulé, rien n'a été touché"))
                return 0
            }
        }

        var moved: [Candidate] = []
        for candidate in removable {
            if let problem = verify(candidate.path, rule: candidate.rule) {
                print("  " + Style.yellow(tr(en: "skipped", fr: "passé")) + "  \(candidate.path)  (\(problem))")
                continue
            }
            do {
                try FileManager.default.trashItem(at: URL(fileURLWithPath: candidate.path),
                                                  resultingItemURL: nil)
                moved.append(candidate)
                print("  " + Style.green(tr(en: "trashed", fr: "corbeille")) + "  \(candidate.path)")
            } catch {
                print("  " + Style.red(tr(en: "failed", fr: "échec")) + "  \(candidate.path)  (\(error.localizedDescription))")
            }
        }
        // The total is recomputed over what actually moved: blocks shared
        // between two of these are freed only because both went, so the figure
        // is not the sum of the parts.
        let freed = combinedFreed(moved, in: result)
        print(tr(en: "\n  %d folders moved, %@ reclaimable once the Trash is emptied",
                 fr: "\n  %d dossiers déplacés, %@ récupérables une fois la corbeille vidée", moved.count, humanBytes(freed)))
        return moved.count
    }
}
